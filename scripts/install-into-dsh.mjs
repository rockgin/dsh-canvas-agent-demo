#!/usr/bin/env node
/**
 * Copies the demo plugin into a DeepSeek Harness checkout and wires it into the
 * repository-wide build, so `pnpm typecheck` / `pnpm build` cover it.
 *
 * Usage:
 *   node scripts/install-into-dsh.mjs /path/to/deepseek-harness
 *   node scripts/install-into-dsh.mjs /path/to/deepseek-harness --force
 *
 * The target path is `packages/client/ui-canvas-agent-demo`, which keeps the
 * package inside the pnpm workspace and next to the shared client bundle
 * preset referenced by `tsdown.config.ts`.
 */
import { cpSync, existsSync, readFileSync, rmSync, writeFileSync } from 'node:fs'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const here = dirname(fileURLToPath(import.meta.url))
const repoRoot = resolve(here, '..')
const source = join(repoRoot, 'packages/client/ui-canvas-agent-demo')

const args = process.argv.slice(2)
const force = args.includes('--force')
const targetRepoArg = args.find((arg) => !arg.startsWith('--'))

if (targetRepoArg === undefined) {
  console.error('Usage: node scripts/install-into-dsh.mjs /path/to/deepseek-harness [--force]')
  process.exit(1)
}

const targetRepo = resolve(targetRepoArg)
const marker = join(targetRepo, 'pnpm-workspace.yaml')
const clientDir = join(targetRepo, 'packages/client')

if (!existsSync(marker) || !existsSync(clientDir)) {
  console.error(`Not a DeepSeek Harness checkout: ${targetRepo}`)
  process.exit(1)
}

const destination = join(clientDir, 'ui-canvas-agent-demo')

if (existsSync(destination)) {
  if (!force) {
    console.error(`Already exists: ${destination}\nRe-run with --force to replace it.`)
    process.exit(1)
  }
  rmSync(destination, { recursive: true, force: true })
}

cpSync(source, destination, {
  recursive: true,
  filter: (path) => !path.includes(`${join(source, 'lib')}`) && !path.includes('node_modules'),
})

/**
 * The client build is driven by explicit references in `tsconfig.client.json`,
 * so a new package is invisible to `pnpm typecheck` and `pnpm build` until it
 * is added there.
 * @returns a short status describing what happened.
 */
function ensureClientReference() {
  const configPath = join(targetRepo, 'tsconfig.client.json')
  if (!existsSync(configPath)) return 'missing tsconfig.client.json'

  const text = readFileSync(configPath, 'utf8')
  if (text.includes('./packages/client/ui-canvas-agent-demo')) return 'already present'

  const anchor = /\{\s*"path":\s*"\.\/packages\/client\/ui-subagent"\s*\},?/
  const match = anchor.exec(text)
  if (match === null) return 'ui-subagent anchor not found'

  const existing = match[0].trimEnd().endsWith(',') ? match[0] : `${match[0]},`
  const entry = '\n    { "path": "./packages/client/ui-canvas-agent-demo" },'
  writeFileSync(configPath, text.replace(anchor, `${existing}${entry}`))
  return 'added'
}

/**
 * The web roster is a composition file, not a directory scan: the plugin only
 * loads at runtime when a row names it. Writing an overlay keeps the checkout
 * untouched; pass it with `--patch`.
 */
function writeOverlay() {
  const overlayPath = join(targetRepo, 'canvas-agent.overlay.yml')
  writeFileSync(
    overlayPath,
    [
      '# Generated by dsh-canvas-agent-demo.',
      '# Pass with: pnpm dsh web --patch ./canvas-agent.overlay.yml',
      '- insert:',
      '    - id: ui-canvas-agent-demo',
      "      name: '@dsh-demo/dsh-client-ui-canvas-agent'",
      '',
    ].join('\n'),
  )
  return overlayPath
}

const reference = ensureClientReference()
const overlay = writeOverlay()

console.log(`Installed demo plugin into ${destination}`)
console.log(`tsconfig.client.json reference: ${reference}`)
console.log(`Web overlay written to ${overlay}`)
console.log('')
console.log('Next steps:')
console.log(`  cd ${targetRepo}`)
console.log('  pnpm install --no-frozen-lockfile')
console.log('  pnpm build')
console.log('  pnpm dsh web --patch ./canvas-agent.overlay.yml --no-open --port 3080')
console.log('')
console.log('The canvas registers itself as the `canvas-agent` main panel.')
